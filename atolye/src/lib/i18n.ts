import { useSyncExternalStore } from 'react'
import { flushSync } from 'react-dom'

/**
 * One global language (Turkish or English) for the whole interface and the content. The dictionary below holds every
 * hard-coded UI string as a [tr, en] pair, so a missing translation is a type error, not a blank in the page.
 * Content files carry their own twins (`prompt`/`prompt_tr`, ...); lib/exercises and lib/cards pick between them.
 */
export type Lang = 'tr' | 'en'

const KEY = 'atolye:lang'
const OLD_KEY = 'atolye:v1'

/** The saved choice; falls back to the old per-exercise switch (settings.lang in the progress file), then to Turkish. */
function read(): Lang {
  try {
    const v = localStorage.getItem(KEY)
    if (v === 'tr' || v === 'en') return v
    const old = JSON.parse(localStorage.getItem(OLD_KEY) || 'null') as { settings?: { lang?: string } } | null
    if (old?.settings?.lang === 'en') {
      localStorage.setItem(KEY, 'en')
      return 'en'
    }
  } catch {
    /* storage unavailable: Turkish for this session */
  }
  return 'tr'
}

let lang: Lang = read()
const subs = new Set<() => void>()

const applyHtml = () => {
  if (typeof document !== 'undefined') document.documentElement.lang = lang
}
applyHtml()

export const getLang = (): Lang => lang
export function setLang(next: Lang) {
  if (next === lang) return
  lang = next
  try {
    localStorage.setItem(KEY, next)
  } catch {
    /* ignore */
  }
  applyHtml()
  subs.forEach((f) => f())
}
/**
 * The switch the learner presses. The page swaps text in a quick crossfade (View Transitions API, 160 ms, see base.css);
 * with reduced motion, or where the API is missing, it swaps at once. `html[data-lang-fade]` records which one ran.
 */
export function switchLang(to: Lang | 'toggle' = 'toggle') {
  const root = document.documentElement
  const apply = () => flushSync(() => setLang(to === 'toggle' ? (lang === 'tr' ? 'en' : 'tr') : to))
  const reduced = typeof matchMedia === 'function' && matchMedia('(prefers-reduced-motion: reduce)').matches
  const doc = document as Document & { startViewTransition?: (cb: () => void) => unknown }
  if (!reduced && typeof doc.startViewTransition === 'function') {
    root.dataset.langFade = 'fade'
    doc.startViewTransition(apply)
  } else {
    root.dataset.langFade = 'instant'
    apply()
  }
}

export const subscribeLang = (f: () => void): (() => void) => {
  subs.add(f)
  return () => subs.delete(f)
}
export const useLang = (): Lang => useSyncExternalStore(subscribeLang, getLang, getLang)

